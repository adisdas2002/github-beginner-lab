export const GLYPH_H = 5;

function glyphWidth(ch) {
  return ch === ' ' ? 2 : 3;
}

export function measureText(text) {
  const s = String(text);
  let w = 0;
  for (const ch of s) w += glyphWidth(ch) + 1;
  return Math.max(0, w - 1);
}

export function drawText(ctx, text, x, y, color) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of String(text).toUpperCase()) {
    const glyph = G[ch];
    if (glyph) {
      for (let row = 0; row < GLYPH_H; row++) {
        for (let col = 0; col < 3; col++) {
          if (glyph[row][col] === '#') ctx.fillRect(cx + col, cy + row, 1, 1);
        }
      }
    }
    cx += glyphWidth(ch) + 1;
  }
}

// Text with a 1px dark shadow, centered on x.
export function drawLabel(ctx, text, centerX, y, color, shadow = '#0b0816') {
  const w = measureText(text);
  const x = Math.round(centerX - w / 2);
  drawText(ctx, text, x + 1, y + 1, shadow);
  drawText(ctx, text, x, y, color);
  return { x, w };
}
